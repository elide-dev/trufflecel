# Regenerates errorprone-default-warnings.txt: Error Prone's default-WARNING checks, as bundled in Bazel's JavaBuilder.
# JavaBuilder runs only an allowlist (mostly default-ERROR checks), while trufflecheck's profile assumes Error Prone's
# defaults; sync_profile.py enables these by name ahead of the profile. Rerun after a rules_java/java_tools upgrade:
#
#   tools/trufflecheck/list_default_warnings.sh && bazel run --config=local //tools/trufflecheck:sync_profile
set -euo pipefail
cd "$(dirname "$0")/../.."
base="$(bazelisk info --config=local output_base 2>/dev/null)"
jar="$base/external/rules_java++toolchains+remote_java_tools/java_tools/JavaBuilder_deploy.jar"
# The source launcher needs jdk.compiler; use the hermetic JDK 25 from rules_java (fetched by any local build).
java=""
for candidate in "$base"/external/rules_java++toolchains+remotejdk25_*/bin/java; do
  [[ -x "$candidate" ]] && { java="$candidate"; break; }
done
[[ -n "$java" ]] || { echo "no remotejdk25 under $base/external; run a --config=local build first" >&2; exit 1; }
version="$(unzip -p "$jar" META-INF/maven/com.google.errorprone/error_prone_core/pom.properties | sed -n 's/^version=//p')"
{
  echo "# Error Prone $version default-WARNING checks (Bazel JavaBuilder). Generated by list_default_warnings.sh."
  "$java" -cp "$jar" tools/trufflecheck/ErrorProneCatalog.java WARNING
} > tools/trufflecheck/errorprone-default-warnings.txt
echo "wrote tools/trufflecheck/errorprone-default-warnings.txt (Error Prone $version)"
