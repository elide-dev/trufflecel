"""Generates tools/trufflecheck/errorprone.bazelrc from trufflecheck's profiles/jvm/errorprone.args.

  bazel run --config=local //tools/trufflecheck:sync_profile                  # rewrite errorprone.bazelrc
  sync_profile.py --check <errorprone.args> <default-warnings> <bazelrc>      # profile_sync_test

The profile is applied verbatim apart from the documented deltas below, so upgrading trufflecheck is: bump the pins in
MODULE.bazel, re-pin @trufflecheck, run this, and review the diff.
"""
import os
import pathlib
import sys

# Checks the profile enables that Bazel's bundled Error Prone (java_tools, currently 2.50.0) does not have; naming an
# unknown check is a hard javac error. Drop entries as java_tools catches up to the profile's Error Prone 2.51.0.
UNSUPPORTED = {"ValueClassIdentity"}

# Repository-specific additions, after the profile so they take precedence.
EXTRA = [
    # Replaces the profile's exclusion: Bazel puts annotation-processor (Truffle DSL, JMH) and srcjar (protobuf) sources
    # under bazel-out/, which the profile's `generated` pattern does not match. Generated code is not ours to fix.
    "-XepExcludedPaths:.*/(generated|third_party|bazel-out)/.*",
    # Policy (and the class-init lists it names) are inputs of every compile via //tools/trufflecheck:errorprone data.
    "-XepOpt:Trufflecheck:Policy=tools/trufflecheck/trufflecheck.properties",
    # javac stops printing after 100 diagnostics per compilation by default; the report needs all of them.
    "-Xmaxwarns", "100000",
    "-Xmaxerrs", "100000",
]

HEADER = """\
# GENERATED by //tools/trufflecheck:sync_profile from trufflecheck's profiles/jvm/errorprone.args. Do not edit;
# change tools/trufflecheck/sync_profile.py or the pinned profile instead (checked by :profile_sync_test).
#
#   --config=trufflecheck         Error Prone + NullAway + trufflecheck at the profile's severities (errors fail).
#   --config=trufflecheck_report  The same, with every error reported as a warning and --keep_going, for reports.
"""


def defaults(warnings_text, profile):
    """Error Prone's default warnings, which Bazel's JavaBuilder leaves off unless named; the profile assumes them."""
    named = {flag.split(":")[1] for flag in profile if flag.startswith("-Xep:")}
    names = [line.strip() for line in warnings_text.splitlines() if line.strip() and not line.startswith("#")]
    return ["-Xep:%s:WARN" % name for name in names if name not in named]


def flags(args_text):
    result = []
    for line in args_text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("-Xep:") and line.split(":")[1] in UNSUPPORTED:
            continue
        result.append(line)
    return result + EXTRA


def render(args_text, warnings_text):
    profile = flags(args_text)
    lines = [HEADER]
    lines.append("build:trufflecheck --plugin=//tools/trufflecheck:errorprone")
    lines.append("# Error Prone default warnings (errorprone-default-warnings.txt), then the trufflecheck profile.")
    lines += ["build:trufflecheck --javacopt=" + flag for flag in defaults(warnings_text, profile)]
    lines.append("# trufflecheck profile.")
    lines += ["build:trufflecheck --javacopt=" + flag for flag in profile]
    lines.append("")
    lines.append("build:trufflecheck_report --config=trufflecheck")
    lines.append("build:trufflecheck_report --javacopt=-XepAllErrorsAsWarnings")
    lines.append("build:trufflecheck_report --keep_going")
    return "\n".join(lines) + "\n"


def main(argv):
    read = lambda path: pathlib.Path(path).read_text(encoding="utf-8")
    if len(argv) == 5 and argv[1] == "--check":
        expected = render(read(argv[2]), read(argv[3]))
        actual = read(argv[4])
        if expected != actual:
            print("errorprone.bazelrc is stale: bazel run --config=local //tools/trufflecheck:sync_profile",
                  file=sys.stderr)
            return 1
        return 0
    if len(argv) == 4:
        workspace = pathlib.Path(os.environ.get("BUILD_WORKSPACE_DIRECTORY", "."))
        (workspace / argv[3]).write_text(render(read(argv[1]), read(workspace / argv[2])), encoding="utf-8")
        print("wrote", argv[3])
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
